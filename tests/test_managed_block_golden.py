"""The managed block's network part, as NixOS evaluates it (task queue item 52).

The flake check ``installed-network-units`` evaluates these golden files, the
managed block exactly as ``install._inject_configuration`` writes it, with
NixOS, and asserts which systemd-networkd units the installed system gets.
This test keeps the golden files equal to what pre-nixos writes, so the check
in Nix and the code in Python cannot drift apart.

To regenerate after an intended change: ``PRE_NIXOS_UPDATE_GOLDEN=1 pytest
tests/test_managed_block_golden.py``, then review the diff.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

import pytest

from pre_nixos import install
from tests.test_install import _make_lan, _sample_storage_plan

REPO = Path(__file__).resolve().parents[1]
GOLDEN_DIR = REPO / "tests" / "fixtures" / "managed-block"
BASE = REPO / "tests" / "fixtures" / "nixos-generate-config" / "efi"
START = "  # pre-nixos auto-install start"
END = "  # pre-nixos auto-install end"

# Values the flake check asserts on; change both together.
STATIC = install.build_install_network_config(
    "192.0.2.10", "255.255.255.0", "192.0.2.1", dns=["192.0.2.53"]
)
VARIANTS = {"dhcp": None, "static": STATIC}


def render(tmp_path: Path, variant: str) -> str:
    """The managed block for *variant*, as a NixOS module."""

    root = tmp_path / "root"
    config_dir = root / "etc" / "nixos"
    config_dir.mkdir(parents=True)
    for name in ("configuration.nix", "hardware-configuration.nix"):
        shutil.copy(BASE / name, config_dir / name)
    lan = _make_lan(tmp_path)
    install._inject_configuration(
        root,
        lan.authorized_key.read_text(),
        lan,
        _sample_storage_plan(),
        VARIANTS[variant],
        console_kernel_params=["console=ttyS0,115200", "console=tty0"],
    )
    text = (config_dir / "configuration.nix").read_text()
    start, end = text.index(START), text.index(END) + len(END)
    return (
        "# Generated by tests/test_managed_block_golden.py from\n"
        "# install._inject_configuration; do not edit (task queue item 52).\n"
        "{ config, lib, pkgs, ... }:\n"
        "{\n"
        f"{text[start:end]}\n"
        "}\n"
    )


@pytest.mark.parametrize("variant", sorted(VARIANTS))
def test_golden_file_matches_what_pre_nixos_writes(tmp_path: Path, variant: str) -> None:
    golden = GOLDEN_DIR / f"{variant}.nix"
    expected = render(tmp_path, variant)
    if os.environ.get("PRE_NIXOS_UPDATE_GOLDEN") == "1":
        golden.parent.mkdir(parents=True, exist_ok=True)
        golden.write_text(expected)
    assert golden.read_text() == expected, (
        f"{golden} is stale; regenerate with PRE_NIXOS_UPDATE_GOLDEN=1 and review the diff"
    )
